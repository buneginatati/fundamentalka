ALTER TABLE public.fundamentals       ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.dividends          ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.insider_trades     ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.corporate_events   ENABLE ROW LEVEL SECURITY;

